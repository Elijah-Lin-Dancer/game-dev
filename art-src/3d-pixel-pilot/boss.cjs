module.exports = ({ makeBuilder, makeSculpt, KIT: K }) => ({
  id: 'mossback-boss', name: '苔背巨兽', seed: 31,
  build(seed) {
    const P = [
      0x140f14, 0x2b1a22, 0x4a2730, 0x73353c, 0xa74a45, 0xd87858,
      0x26351f, 0x3e542b, 0x5f753a, 0x91a84e, 0xc7bd6a,
      0xd9c79a, 0xf2e6c1, 0x7c5439, 0x493125, 0xffc14d, 0x2a3037
    ];
    const B = makeBuilder(seed, P);
    const S = K.sculpt(makeSculpt(B));
    const body = { r: [2,3,4,5] };
    const dark = { r: [0,1,2] };
    const moss = { r: [6,7,8,9] };
    const mossLight = { r: [8,9,10] };
    const bone = { r: [11,12] };
    const horn = { r: [11,12,0] };
    const claw = { r: [12,11,0] };
    const eye = { r: [15], em: true };
    const socket = { r: [0,1] };
    const leather = { r: [13,14,2] };

    // torso and belly
    S.ball([0, 1.20, 0.10], [1.35, 1.02, 1.08], body, { res: 0.045, rd: 0.16 });
    S.ball([0, 0.82, 0.58], [0.78, 0.52, 0.48], { r: [4,5,12] }, { res: 0.055, rd: 0.12 });
    // mossy back shell
    S.rock([0, 1.78, -0.26], [1.28, 0.55, 1.02], moss, { res: 0.05 });
    S.rock([-0.34, 1.95, -0.25], [0.68, 0.30, 0.78], mossLight, { res: 0.055 });
    S.rock([0.38, 1.88, -0.44], [0.52, 0.26, 0.58], { r: [7,8,9] }, { res: 0.05 });
    // head
    S.ball([0, 1.38, 1.12], [0.70, 0.58, 0.62], { r: [2,3,4] }, { res: 0.045, rd: 0.12 });
    S.ball([0, 0.94, 1.42], [0.56, 0.29, 0.42], { r: [3,4,12] }, { res: 0.05, rd: 0.12 });
    S.ball([0, 1.21, 1.52], [0.22, 0.18, 0.16], { r: [1,2,12] }, { res: 0.035 });
    // eye sockets and ember eyes
    S.ball([-0.31, 1.55, 1.72], [0.23, 0.18, 0.06], socket, { res: 0.03 });
    S.ball([0.31, 1.55, 1.72], [0.23, 0.18, 0.06], socket, { res: 0.03 });
    S.ball([-0.30, 1.58, 1.78], [0.085, 0.075, 0.065], eye, { res: 0.02 });
    S.ball([0.30, 1.58, 1.78], [0.085, 0.075, 0.065], eye, { res: 0.02 });
    // brow rocks
    S.box([-0.34, 1.76, 1.52], [0.34, 0.12, 0.20], dark, { res: 0.04, rd: 0.11 });
    S.box([0.34, 1.76, 1.52], [0.34, 0.12, 0.20], dark, { res: 0.04, rd: 0.11 });
    // horn pair and tusks
    S.tube([[-0.47,1.71,1.27],[-0.68,1.95,1.32],[-0.82,2.25,1.20],[-0.74,2.46,1.03]], 0.15, 0.035, horn, { res: 0.035 });
    S.tube([[0.47,1.71,1.27],[0.68,1.95,1.32],[0.82,2.25,1.20],[0.74,2.46,1.03]], 0.15, 0.035, horn, { res: 0.035 });
    S.tube([[-0.45,1.05,1.48],[-0.72,1.22,1.60],[-0.92,1.44,1.55]], 0.12, 0.035, claw, { res: 0.035 });
    S.tube([[0.45,1.05,1.48],[0.72,1.22,1.60],[0.92,1.44,1.55]], 0.12, 0.035, claw, { res: 0.035 });
    // nostrils
    S.ball([-0.16, 1.16, 1.82], [0.055, 0.045, 0.03], dark, { res: 0.02 });
    S.ball([0.16, 1.16, 1.82], [0.055, 0.045, 0.03], dark, { res: 0.02 });
    S.box([-0.24, 1.02, 1.80], [0.07, 0.12, 0.04], claw, { res: 0.02, rd: 0.03 });
    S.box([0.24, 1.02, 1.80], [0.07, 0.12, 0.04], claw, { res: 0.02, rd: 0.03 });
    // legs and feet
    for (const sx of [-1, 1]) {
      S.box([sx*0.86, 0.52, 0.62], [0.38, 0.43, 0.40], { r: [2,3,4] }, { res: 0.05, rd: 0.12 });
      S.box([sx*0.92, 0.17, 0.74], [0.45, 0.18, 0.55], { r: [2,3,4] }, { res: 0.05, rd: 0.10 });
      S.tube([[sx*1.20,0.10,0.88],[sx*1.44,0.08,0.98]], 0.08, 0.02, claw, { res: 0.03 });
      S.tube([[sx*1.08,0.10,1.02],[sx*1.28,0.08,1.14]], 0.08, 0.02, claw, { res: 0.03 });
      S.box([sx*0.70, 0.42, -0.82], [0.32, 0.35, 0.35], { r: [1,2,3] }, { res: 0.05, rd: 0.11 });
      S.box([sx*0.76, 0.13, -0.86], [0.38, 0.14, 0.42], { r: [1,2,3] }, { res: 0.05, rd: 0.09 });
    }
    // tail
    S.tube([[0,0.98,-0.88],[0,0.72,-1.25],[-0.15,0.48,-1.48],[-0.43,0.35,-1.55]], 0.24, 0.07, { r: [2,3,4] }, { res: 0.04 });
    // moss tufts
    for (const [x,y,z,s] of [[-0.75,2.05,0.1,0.24],[0.1,2.15,-0.55,0.3],[0.72,1.86,-0.2,0.22],[-0.1,2.05,0.55,0.2]]) {
      S.rock([x,y,z], [s, s*0.55, s*0.8], mossLight, { res: 0.04 });
    }
    // leather harness / straps
    S.tube([[-1.02,1.55,0.55],[-0.2,1.32,0.86],[0.85,1.50,0.55]], 0.09, 0.09, leather, { res: 0.035 });
    S.ball([0.0,1.30,0.93], 0.16, { r: [10,12] }, { res: 0.035 });
    S.bake();
    return B.finish({ cam: { target: [0, 1.25, 0.35], dist: 6.4, pitch: 0.20, yaw: 0.35 }, detail: 16, dither: 0.28, radius: 5 });
  }
});
